-- 1. PROFILES TABLE (Linked directly to Supabase Auth)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    username VARCHAR(50) UNIQUE NOT NULL,
    display_name VARCHAR(100),
    avatar_url TEXT DEFAULT '',
    avatar_color VARCHAR(10) DEFAULT '#00d4ff',
    bio TEXT DEFAULT '',
    total_gestures INT DEFAULT 0,
    total_sessions INT DEFAULT 0,
    total_usage_minutes FLOAT DEFAULT 0.0,
    preferred_mode VARCHAR(20) DEFAULT 'DESKTOP',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. USER SETTINGS TABLE
CREATE TABLE IF NOT EXISTS public.user_settings (
    user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    theme VARCHAR(30) DEFAULT 'dark',
    assistant_name VARCHAR(50) DEFAULT 'Nova',
    voice_gender VARCHAR(10) DEFAULT 'female',
    mouse_speed INT DEFAULT 12,
    scroll_speed INT DEFAULT 20,
    gesture_sensitivity INT DEFAULT 5,
    shortcuts_enabled BOOLEAN DEFAULT TRUE,
    mirror_camera BOOLEAN DEFAULT TRUE,
    face_blur BOOLEAN DEFAULT FALSE,
    audio_enabled BOOLEAN DEFAULT FALSE,
    audio_volume INT DEFAULT 80,
    fps_limit INT DEFAULT 30,
    settings_json JSONB DEFAULT '{}'::JSONB,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. CUSTOM GESTURES TABLE (3D Landmark Signatures)
CREATE TABLE IF NOT EXISTS public.custom_gestures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    name VARCHAR(60) NOT NULL,
    mode VARCHAR(20) NOT NULL DEFAULT 'DESKTOP', -- 'DESKTOP', 'GAMING', 'DRAW'
    action_type VARCHAR(30) NOT NULL,            -- 'HOTKEY', 'KEY_PRESS', 'MOUSE_CLICK'
    action_target VARCHAR(100) NOT NULL,         -- 'win+shift+s', 'left', 'ctrl+c'
    signature JSONB NOT NULL,                   -- Array of 21 3D points [{x, y, z}]
    threshold INT DEFAULT 75,
    is_enabled BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. CALIBRATION PROFILES TABLE
CREATE TABLE IF NOT EXISTS public.calibration_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    profile_name VARCHAR(60) DEFAULT 'Default Calibration',
    screen_width INT DEFAULT 1920,
    screen_height INT DEFAULT 1080,
    margin_x_min INT DEFAULT 100,
    margin_x_max INT DEFAULT 540,
    margin_y_min INT DEFAULT 100,
    margin_y_max INT DEFAULT 380,
    smooth_factor FLOAT DEFAULT 0.5,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. TRAINING & GAMING STATS TABLE
CREATE TABLE IF NOT EXISTS public.training_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    mode_name VARCHAR(50) NOT NULL,             -- 'CYBER_RUNNER', 'REFLEX_CHALLENGE', 'AI_TRAINER'
    score INT DEFAULT 0,
    accuracy_pct FLOAT DEFAULT 0.0,
    gestures_recognized INT DEFAULT 0,
    duration_seconds INT DEFAULT 0,
    played_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 6. ACTIVITY LOGS TABLE
CREATE TABLE IF NOT EXISTS public.activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    action_type VARCHAR(50) NOT NULL,
    details TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ==============================================================================
-- 🔒 ROW LEVEL SECURITY (RLS) POLICIES
-- Each user can only view, edit, and delete their own data
-- ==============================================================================

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.custom_gestures ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.calibration_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.training_stats ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.activity_logs ENABLE ROW LEVEL SECURITY;

-- Profiles Policies
CREATE POLICY "Users can view own profile" ON public.profiles FOR SELECT USING (auth.uid() = id);
CREATE POLICY "Users can update own profile" ON public.profiles FOR UPDATE USING (auth.uid() = id);
CREATE POLICY "Users can insert own profile" ON public.profiles FOR INSERT WITH CHECK (auth.uid() = id);

-- User Settings Policies
CREATE POLICY "Users can view own settings" ON public.user_settings FOR ALL USING (auth.uid() = user_id);

-- Custom Gestures Policies
CREATE POLICY "Users can manage own gestures" ON public.custom_gestures FOR ALL USING (auth.uid() = user_id);

-- Calibration Policies
CREATE POLICY "Users can manage own calibration" ON public.calibration_profiles FOR ALL USING (auth.uid() = user_id);

-- Training Stats Policies
CREATE POLICY "Users can manage own stats" ON public.training_stats FOR ALL USING (auth.uid() = user_id);

-- Activity Logs Policies
CREATE POLICY "Users can manage own logs" ON public.activity_logs FOR ALL USING (auth.uid() = user_id);

-- ==============================================================================
-- ⚡ AUTOMATIC PROFILE CREATION TRIGGER ON SIGNUP
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, username, display_name)
    VALUES (
        NEW.id,
        REGEXP_REPLACE(COALESCE(NEW.raw_user_meta_data->>'username', split_part(NEW.email, '@', 1)), '[0-9]', '', 'g'),
        REGEXP_REPLACE(
            COALESCE(
                NEW.raw_user_meta_data->>'full_name',
                NEW.raw_user_meta_data->>'name',
                NEW.raw_user_meta_data->>'display_name',
                split_part(NEW.email, '@', 1)
            ),
            '[0-9]',
            '',
            'g'
        )
    );

    INSERT INTO public.user_settings (user_id)
    VALUES (NEW.id);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Drop existing trigger if exists
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;

-- Create trigger
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
